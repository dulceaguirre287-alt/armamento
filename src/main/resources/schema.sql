CREATE TABLE IF NOT EXISTS almacen (
    id_almacen INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    direccion VARCHAR(500),
    ciudad VARCHAR(150),
    responsable INTEGER,
    activo BOOLEAN
);

CREATE TABLE IF NOT EXISTS auditoria (
    id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER,
    accion VARCHAR(100),
    tabla VARCHAR(150),
    registro_id VARCHAR(100),
    datos_antes CLOB,
    datos_despues CLOB,
    ip_origen VARCHAR(64),
    fecha TIMESTAMP
);

CREATE TABLE IF NOT EXISTS categoria (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    tipo_control VARCHAR(100),
    requiere_permiso BOOLEAN,
    descripcion CLOB,
    activo BOOLEAN
);

CREATE TABLE IF NOT EXISTS cliente (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_cliente VARCHAR(100),
    tipo_documento VARCHAR(100),
    numero_documento VARCHAR(100),
    nombre_razon VARCHAR(255),
    email VARCHAR(255),
    telefono VARCHAR(100),
    direccion VARCHAR(500),
    ciudad VARCHAR(150),
    activo BOOLEAN,
    creado_en TIMESTAMP
);

CREATE TABLE IF NOT EXISTS compra (
    id_compra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_compra VARCHAR(100),
    id_proveedor INTEGER,
    id_almacen INTEGER,
    id_usuario INTEGER,
    fecha_compra DATE,
    fecha_recepcion TIMESTAMP,
    numero_factura_proveedor VARCHAR(150),
    guia_transporte VARCHAR(150),
    subtotal DECIMAL(19, 4),
    descuento DECIMAL(19, 4),
    iva DECIMAL(19, 4),
    total DECIMAL(19, 4),
    estado VARCHAR(100),
    observaciones CLOB,
    creado_en TIMESTAMP
);

CREATE TABLE IF NOT EXISTS detalle_compra (
    id_detalle_compra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra BIGINT,
    id_producto INTEGER,
    cantidad_pedida INTEGER,
    cantidad_recibida INTEGER,
    precio_unitario DECIMAL(19, 4),
    porcentaje_iva DECIMAL(9, 4),
    lote VARCHAR(150),
    fecha_vencimiento DATE,
    subtotal DECIMAL(19, 4)
);

CREATE TABLE IF NOT EXISTS detalle_devolucion (
    id_detalle_devolucion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_devolucion BIGINT,
    id_producto INTEGER,
    id_unidad BIGINT,
    lote VARCHAR(150),
    cantidad INTEGER,
    precio_unitario DECIMAL(19, 4),
    condicion VARCHAR(100),
    reingresa_stock BOOLEAN
);

CREATE TABLE IF NOT EXISTS detalle_venta (
    id_detalle_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta BIGINT,
    id_producto INTEGER,
    cantidad INTEGER,
    precio_unitario DECIMAL(19, 4),
    descuento DECIMAL(19, 4),
    porcentaje_iva DECIMAL(9, 4),
    lote VARCHAR(150),
    subtotal DECIMAL(19, 4)
);

CREATE TABLE IF NOT EXISTS devolucion (
    id_devolucion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_devolucion VARCHAR(100),
    tipo VARCHAR(100),
    id_venta BIGINT,
    id_compra BIGINT,
    id_almacen INTEGER,
    id_usuario INTEGER,
    fecha_devolucion TIMESTAMP,
    motivo VARCHAR(255),
    descripcion CLOB,
    total_reembolso DECIMAL(19, 4),
    estado VARCHAR(100),
    aprobada_por INTEGER
);

CREATE TABLE IF NOT EXISTS existencia (
    id_existencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto INTEGER,
    id_almacen INTEGER,
    lote VARCHAR(150),
    fecha_vencimiento DATE,
    cantidad INTEGER,
    actualizado_en TIMESTAMP
);

CREATE TABLE IF NOT EXISTS marca (
    id_marca INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    pais_origen VARCHAR(150),
    activo BOOLEAN
);

CREATE TABLE IF NOT EXISTS movimiento_inventario (
    id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto INTEGER,
    id_almacen INTEGER,
    id_unidad BIGINT,
    lote VARCHAR(150),
    tipo_movimiento VARCHAR(100),
    cantidad INTEGER,
    saldo_posterior INTEGER,
    costo_unitario DECIMAL(19, 4),
    referencia_tipo VARCHAR(100),
    referencia_id BIGINT,
    id_usuario INTEGER,
    fecha TIMESTAMP,
    observaciones CLOB
);

CREATE TABLE IF NOT EXISTS permiso_cliente (
    id_permiso INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INTEGER,
    tipo_permiso VARCHAR(100),
    numero_permiso VARCHAR(150),
    autoridad_emisora VARCHAR(255),
    fecha_expedicion DATE,
    fecha_vencimiento DATE,
    estado VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS producto_proveedor (
    id_producto INTEGER NOT NULL,
    id_proveedor INTEGER NOT NULL,
    codigo_proveedor VARCHAR(150),
    ultimo_precio DECIMAL(19, 4),
    dias_entrega SMALLINT,
    PRIMARY KEY (id_producto, id_proveedor)
);

CREATE TABLE IF NOT EXISTS producto (
    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(100),
    nombre VARCHAR(255),
    descripcion CLOB,
    id_categoria INTEGER,
    id_marca INTEGER,
    modelo VARCHAR(150),
    calibre VARCHAR(100),
    unidad_medida VARCHAR(100),
    controla_serial BOOLEAN,
    controla_lote BOOLEAN,
    precio_compra_ref DECIMAL(19, 4),
    precio_venta DECIMAL(19, 4),
    porcentaje_iva DECIMAL(9, 4),
    stock_minimo INTEGER,
    activo BOOLEAN,
    creado_en TIMESTAMP,
    actualizado_en TIMESTAMP
);

CREATE TABLE IF NOT EXISTS proveedor (
    id_proveedor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razon_social VARCHAR(255),
    nit VARCHAR(100),
    numero_licencia VARCHAR(150),
    licencia_vence DATE,
    contacto_nombre VARCHAR(255),
    email VARCHAR(255),
    telefono VARCHAR(100),
    direccion VARCHAR(500),
    ciudad VARCHAR(150),
    pais VARCHAR(150),
    condiciones_pago VARCHAR(255),
    activo BOOLEAN,
    creado_en TIMESTAMP,
    actualizado_en TIMESTAMP
);

CREATE TABLE IF NOT EXISTS rol (
    id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150),
    descripcion CLOB
);

CREATE TABLE IF NOT EXISTS unidad_seriada (
    id_unidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto INTEGER,
    numero_serie VARCHAR(150),
    id_almacen INTEGER,
    id_detalle_compra BIGINT,
    id_detalle_venta BIGINT,
    estado VARCHAR(100),
    fecha_ingreso TIMESTAMP,
    fecha_salida TIMESTAMP,
    observaciones CLOB
);

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol INTEGER,
    tipo_documento VARCHAR(100),
    numero_documento VARCHAR(100),
    nombres VARCHAR(255),
    apellidos VARCHAR(255),
    email VARCHAR(255),
    telefono VARCHAR(100),
    username VARCHAR(150),
    password_hash VARCHAR(255),
    intentos_fallidos INTEGER,
    bloqueado_hasta TIMESTAMP,
    ultimo_acceso TIMESTAMP,
    activo BOOLEAN,
    creado_en TIMESTAMP,
    actualizado_en TIMESTAMP
);

CREATE TABLE IF NOT EXISTS venta (
    id_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_venta VARCHAR(100),
    id_cliente INTEGER,
    id_usuario INTEGER,
    id_almacen INTEGER,
    id_permiso INTEGER,
    fecha_venta TIMESTAMP,
    subtotal DECIMAL(19, 4),
    descuento DECIMAL(19, 4),
    iva DECIMAL(19, 4),
    total DECIMAL(19, 4),
    metodo_pago VARCHAR(100),
    estado VARCHAR(100),
    autorizada_por INTEGER,
    fecha_autorizacion TIMESTAMP,
    observaciones CLOB
);
